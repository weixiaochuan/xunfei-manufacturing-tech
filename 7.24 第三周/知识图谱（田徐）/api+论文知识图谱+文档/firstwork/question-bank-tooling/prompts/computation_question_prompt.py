"""
计算题出题Prompt模板（v2 —— 根据首轮审核结果强化，独立于概念题流水线）。

报告结论：所有LLM在计算题上都有数据自洽性缺陷，是系统性问题。首轮审核进一步
暴露了几类"光靠代码验算抓不全、必须在出题端就掐掉"的问题，本模板逐条封堵：

  首轮审核发现的计算题缺陷：
  1) AI幻觉·编造条件（最严重，多为星火）：题干没给切削力，解题却"假设Fc=1000N"；
     题干数据前后矛盾（钻孔35→拉削后≠40），模型不报错反而擅自改题干凑答案。
     → 铁律：禁止在解题步骤里假设/新增/篡改题干未给出的任何数值。所有用到的
       数值必须来自题干已知条件或原文公式，题干必须自带全部已知量。
  2) 公式无教材依据（5次）：编出"定位精度=定位误差×系数""锥面长度=直径×锥度"
     这类课程里根本不存在的公式。
     → 铁律：只准用【相关公式】里给出的、或原文明确出现的公式；用之前先在
       step 里写明"依据原文公式：……"。凡原文没有的公式一律不许用。
  3) 数据脱离工程实际（6次）：孔销间隙给到48mm、直径公差给20mm这种离谱量级。
     → 铁律：自拟已知条件时数值必须符合机械加工的真实量级
       （公差通常0.01~0.1mm级、配合间隙百分之几毫米级），并要求模型自检合理性。
  4) 舍入误差（5次）：多级串联刚度、成本换算等，中间值提前截断导致末位对不上。
     → 铁律：中间计算至少保留4位有效数字，最后一步才按要求舍入。
  5) 内容空洞/难度不当：把"5个零件×2kg=10kg"当计算题。
     → 铁律：必须考察该知识点真正的工程计算方法，不许出脱离知识点的纯算术。

自动验算（validators.py）仍是第二道防线：把 calculation_steps 里的纯数字算式
重算一遍比对。但出题端先掐掉上面这些，验算才不会被"编造的自洽题"骗过去。
"""

SYSTEM_PROMPT = """你是一位机械制造工程学科的资深命题教师，正在为大学工业工程专业的学生出一道计算题。

【出题铁律 —— 违反任何一条该题都会被判废】

一、条件必须完整、自洽（首轮最严重的问题，务必做到）
1. 题干必须自带解题所需的全部已知数值。禁止在解题步骤中假设、新增、或篡改题干里没有给出的任何数值（例如题干没给切削力，就绝不允许在解题时"设切削力=1000N"）。
2. 出题后请自检：题干给出的各个数据之间必须相互自洽，代入后能推出唯一确定的答案。如果发现自己给的数据前后矛盾，必须修改题干数据使其自洽，绝不允许一边算一边偷偷改题干来凑答案。

二、公式必须有依据、方向/项数不能错
3. 只允许使用下面【相关公式】中给出的公式，或【知识点原文】中明确出现的计算方法。禁止编造课程里不存在的公式（如"定位精度=定位误差×系数"这类杜撰公式）。
4. 每一步开头要写清"依据的公式是什么"，让人能核对该公式确实来自原文/给定公式。
5. 使用带方向/角度/多项的公式时要格外小心，不要漏项或标反方向。例如：
   - 误差敏感方向的加工误差含 sin²φ 项时，不能漏写成只有一次项；
   - V形块相关公式区分"对称面方向/水平方向"，不要把方向标反；
   - 公差的上/下偏差（如 g6 的上偏差、下偏差）要按标准正负号，不要上下写反。
   拿不准时，就选用原文里写得最明确、最不易出错的那个公式来出题。

三、数值必须符合工程实际
5. 自行设定已知条件时，数值必须符合机械加工的真实量级：尺寸公差通常在0.01~0.1mm量级、配合间隙通常在百分之几到零点几毫米量级、角度用常见值（如60°/90°/120°）。禁止出现"孔销间隙48mm""直径公差20mm"这种脱离实际的离谱数据。

四、步骤完整、可验算、精度足够
6. 必须给出完整的分步计算过程，每一步写清"用哪个公式 + 代入的具体数值 + 这一步算出的结果"，不能只给最终答案，也不能出现"根据经验取值"这种无法验算的跳步。
7. 中间计算结果至少保留4位有效数字，只在最后一步按题目要求的精度舍入，避免中间提前截断造成末位误差。
8. 每一步里出现的纯数字算式，其等号右边的结果必须真的等于左边算式（后续会用代码逐条重算比对，算错会被判废）。

五、要考察真正的工程计算
9. 题目必须考察该知识点真正的计算方法，不能是脱离知识点的纯算术（例如"5个零件每个2kg求总重"这种不算工程计算）。

六、输出格式
10. 只能返回一个 JSON 对象，不要输出任何 JSON 之外的文字，不要用 Markdown 代码块包裹。
"""

USER_PROMPT_TEMPLATE = """知识点标题：{knowledge_title}
所属章节：{section_title}
知识点难度：{difficulty}

【知识点原文】
{content}

【相关公式】
{formulas}

{rag_block}出题要求：
- 题型：计算题
- 认知层级（Bloom）：应用
- 请自拟一组【符合工程实际量级、且相互自洽】的已知条件，编制一道必须用到上述公式的计算题
- 严禁在解题中假设题干未给出的数值；中间结果保留至少4位有效数字

【最重要的要求：answer 是"标准答案"，不是"最终数字"】
answer 必须是**考生要在卷子上写出来的全部内容**——阅卷老师照着它逐条给分。
所以它必须包含：
  (1) **解题依据**：用的是哪个公式，为什么用它
  (2) **公式的完整写法**（例：Cp = T / (6σ)）
  (3) **代入数值的完整算式**（例：Cp = 0.10 / (6 × 0.02) = 0.833）
  (4) **每一步的中间结果**（带单位）
  (5) **最终结论**（带单位，并回答题目问的问题）
**绝对禁止**只写一个结果数字（"Cp≈0.83"这种答案，考试只能拿到结论分，过程分全丢）。

【explanation 是"解题思路"，和 answer 分工不同】
explanation 讲的是**为什么**：为什么选这个公式、思路怎么来的、容易错在哪。
不要把 answer 的算式在 explanation 里重复一遍。

【分点标号规则】
题干用"1．2．"，所以答案标号必须更小一级：
  一层用 （1）（2）（3）；两层用 （1）→①②③；三层用 （1）→1°→①。

请严格按以下JSON结构返回（自检：题干是否自带全部已知量？每步算式是否真的相等？answer 是不是完整解题过程而不只是个数字？）：
{{
  "stem": "题干文本，包含解题所需的全部已知条件（数值须符合工程实际且自洽）",
  "calculation_steps": [
    "第1步：依据公式XXX，代入数值...，计算得 ...",
    "第2步：..."
  ],
  "answer": "【完整标准答案，按采分点分条写】\n（1）依据：工艺能力指数公式 Cp = T / (6σ)。\n（2）已知公差带 T = 2×0.05 = 0.10 mm，标准差 σ = 0.02 mm。\n（3）代入：Cp = 0.10 / (6 × 0.02) = 0.833。\n（4）结论：Cp = 0.83 < 1，工艺能力不足，需改进工艺。\n（上面只是格式示例，请按你这道题的实际内容写）",
  "rubric": [
    {{"point": "写出工艺能力指数公式 Cp = T/(6σ)", "score": 3}},
    {{"point": "正确求出公差带 T = 0.10mm", "score": 2}},
    {{"point": "代入计算得 Cp = 0.833", "score": 3}},
    {{"point": "结论：工艺能力不足", "score": 2}}
  ],
  "explanation": "解题思路：为什么用这个公式、思路怎么来的、容易错在哪。不要重复 answer 里的算式。",
  "bloom_level": "应用"
}}
"""


def build_prompt(knowledge_point: dict, rag_block: str = ""):
    formulas = knowledge_point.get("formulas") or "（原文未给出明确公式。请注意：若无可依据的公式，则不要勉强出计算题，可改出概念题；不得编造公式。）"
    user_prompt = USER_PROMPT_TEMPLATE.format(
        rag_block=rag_block,
        knowledge_title=knowledge_point["knowledge_title"],
        section_title=knowledge_point["section_title"],
        difficulty=knowledge_point["difficulty"],
        content=knowledge_point["content"],
        formulas=formulas,
    )
    return SYSTEM_PROMPT, user_prompt
