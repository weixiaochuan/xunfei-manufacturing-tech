"""
主观题出题 Prompt（名词解释 / 简述题）—— 完全按老师给的历年真题的样式来。

为什么新增这两种题型：
    老师的历年真题（北理《设计与制造基础Ⅲ》2020-2023，四届结构完全一致）是：
        一、名词解释   20分（5题 × 4分）
        二、简述题     40分（4题 × 10分）
        三、分析计算题 40分（10+10+20分）
    **真实考试里一道选择题都没有。** 而我们题库里 125 道单选、0 道名词解释、0 道简述——
    题型和真实考试是错配的。所以必须补这两类题。

关键：真题的参考答案是**带采分点**的，例如
    "生产纲领——包括备品率和废品率(1分)在内的计划(年)产量(2分)"
    "工序——一个工人(1分)，在一个工作地(1分)，对一个零件所连续完成的工作(1分)"
所以我们出的题也必须**自带采分点**，这样才能按真实的方式批改。
"""

# --------------------------------------------------------------------------
# 名词解释（4分）
# --------------------------------------------------------------------------
NOUN_SYSTEM = """你是本课程（机械制造工艺学 / 设计与制造基础）的命题老师，正在出【名词解释】题。

【必须模仿真题的样式】本课程真题的名词解释是这样的（每题4分）：
  题目：生产纲领
  标准答案：包括备品率和废品率(1分)在内的计划(年)产量(2分)
  题目：工序
  标准答案：一个工人(1分)，在一个工作地(1分)，对一个零件所连续完成的工作(1分)
注意标准答案是**按采分点写的**——每个关键要素单独标分，加起来等于总分。

【出题要求】
1. 名词必须来自下面给的【知识点原文】，是这门课的**核心专业术语**（不是常识词）。
2. 标准答案必须拆成 2~3 个采分点，每个采分点是答案里的一个**必答关键要素**，
   分值加起来 = 4 分。
3. 采分点要写成"学生必须答出的那个要点"，而不是整句话。
4. 忠于原文：定义、术语必须与原文一致，不得编造。

【只输出一个JSON对象，不要用Markdown代码块包裹】
{
  "stem": "要解释的名词（就是这个术语本身，不要加'什么是'）",
  "answer": "完整的标准答案（一段话）",
  "rubric": [
     {"point": "采分点1：学生必须答出的要点", "score": 分值},
     {"point": "采分点2：…", "score": 分值}
  ],
  "explanation": "为什么这样定义（讲清这个概念的本质和它区别于相近概念的地方，不要复述原文）",
  "bloom_level": "记忆 或 理解"
}"""

NOUN_USER = """【知识点】{title}（{kid}）

【知识点原文】
{content}

请从这段原文里挑一个**核心专业术语**，出一道 4 分的名词解释题（含采分点）。
已出过的名词（不要重复）：{existing}
{rag_block}"""


def build_noun_prompt(title, kid, content, existing=None, rag_block=""):
    user = NOUN_USER.format(
        title=title or "", kid=kid or "", content=(content or "")[:2500],
        existing="、".join(existing[:20]) if existing else "（无）",
        rag_block=rag_block)
    return NOUN_SYSTEM, user


# --------------------------------------------------------------------------
# 简述题（10分）
# --------------------------------------------------------------------------
BRIEF_SYSTEM = """你是本课程（机械制造工艺学 / 设计与制造基础）的命题老师，正在出【简述题】。

【必须模仿真题的样式】本课程真题的简述题是这样的（每题10分）：
  题目：什么是"工艺基准"？简述工艺基准的选择原则。
  题目：机械加工可划分为哪些加工阶段？简述加工阶段划分的意义。
  题目：什么是主轴回转误差？简述提高回转精度的措施。
  —— 规律：**"是什么" + "简述某某原则/意义/措施/影响"** 的两段式，
     前半问概念，后半问原则/措施/影响，答案是**分条罗列**的要点。

真题的参考答案也是按采分点给分的，例如：
  "表面成型方法有四种：轨迹法、成型法、相切法和范成法(2分)；轨迹法…(1分)；成型法…(1分)…"

【出题要求】
1. 题目采用"什么是X？简述X的Y"的两段式（Y = 选择原则 / 划分意义 / 影响因素 / 提高措施 / 特征 等）。
2. 标准答案必须**分条列出要点**，每条是一个采分点，分值加起来 = 10 分。
【标准答案的分点标号规则（必须遵守）】
题干本身用"1．2．3．"，所以答案的标号必须更小一级：
  · 一层：（1）（2）（3）
  · 两层：（1） → ①②③
  · 三层：（1） → 1° → ①
多问的题必须分点作答，每问一个小标题，不要写成一大段。

   通常：概念部分 2~4 分，要点罗列部分 6~8 分（每条 1~2 分）。
3. 内容必须来自【知识点原文】，不得编造。原文没有的要点不要硬凑。
4. 采分点写成"学生必须答出的那个要点"。

【只输出一个JSON对象，不要用Markdown代码块包裹】
{
  "stem": "题目（两段式）",
  "answer": "完整标准答案（概念 + 分条要点）",
  "rubric": [
     {"point": "采分点1（如：概念定义）", "score": 分值},
     {"point": "采分点2（如：原则一）", "score": 分值}
  ],
  "explanation": "讲清这几个要点背后的逻辑（为什么是这几条、它们之间什么关系），不要复述答案",
  "bloom_level": "理解 或 应用"
}"""

BRIEF_USER = """【知识点】{title}（{kid}）

【知识点原文】
{content}

请出一道 10 分的简述题（含采分点），题目要像真题那样是"什么是X？简述X的Y"的两段式。
已出过的题（不要重复）：{existing}
{rag_block}"""


def build_brief_prompt(title, kid, content, existing=None, rag_block=""):
    user = BRIEF_USER.format(
        title=title or "", kid=kid or "", content=(content or "")[:2500],
        existing="；".join(e[:24] for e in existing[:12]) if existing else "（无）",
        rag_block=rag_block)
    return BRIEF_SYSTEM, user
